#!/usr/bin/env python3
"""Generate Go and Python SDK model types from the OpenAPI schemas."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import subprocess
import sys

import yaml


ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "docs" / "openapi.yaml"
GO_OUTPUT = ROOT / "sdk-go" / "models.gen.go"
PY_OUTPUT = ROOT / "sdk-python" / "src" / "fluxa" / "models.py"


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.replace("-", "_").split("_"))


def referenced_type(schema: dict) -> str | None:
    ref = schema.get("$ref")
    if ref:
        return ref.rsplit("/", 1)[-1]
    for part in schema.get("allOf", []):
        if "$ref" in part:
            return part["$ref"].rsplit("/", 1)[-1]
    return None


def go_type(schema: dict) -> str:
    ref = referenced_type(schema)
    if ref:
        return ref
    kind = schema.get("type")
    if kind == "array":
        return "[]" + go_type(schema.get("items", {}))
    if kind == "object":
        value = schema.get("additionalProperties")
        return "map[string]" + go_type(value) if isinstance(value, dict) else "map[string]any"
    return {
        "string": "string",
        "integer": "int64",
        "number": "float64",
        "boolean": "bool",
    }.get(kind, "any")


def python_type(schema: dict) -> str:
    ref = referenced_type(schema)
    if ref:
        return ref
    kind = schema.get("type")
    if kind == "array":
        return f"list[{python_type(schema.get('items', {}))}]"
    if kind == "object":
        value = schema.get("additionalProperties")
        return f"dict[str, {python_type(value)}]" if isinstance(value, dict) else "dict[str, Any]"
    return {
        "string": "str",
        "integer": "int",
        "number": "float",
        "boolean": "bool",
    }.get(kind, "Any")


_GO_SCALARS = {
    "string": "string",
    "integer": "int64",
    "number": "float64",
    "boolean": "bool",
}

_PY_SCALARS = {
    "string": "str",
    "integer": "int",
    "number": "float",
    "boolean": "bool",
}


def scalar_alias(schema: dict) -> tuple[str | None, str]:
    """Return the (Go, Python) alias for a schema that is not a struct.

    Covers the two shapes that carry no properties: a bare scalar such as a
    string enum, and a free-form object declared with additionalProperties.
    Returns (None, "") when the schema should still be emitted as a struct.
    """
    kind = schema.get("type")
    if kind in _GO_SCALARS:
        return _GO_SCALARS[kind], _PY_SCALARS[kind]
    if kind == "object":
        value = schema.get("additionalProperties")
        if isinstance(value, dict):
            return f"map[string]{go_type(value)}", f"dict[str, {python_type(value)}]"
        return "map[string]any", "dict[str, Any]"
    if kind == "array":
        items = schema.get("items", {})
        return f"[]{go_type(items)}", f"list[{python_type(items)}]"
    return "map[string]any", "dict[str, Any]"


def properties(schema: dict) -> dict:
    result = dict(schema.get("properties", {}))
    for part in schema.get("allOf", []):
        result.update(part.get("properties", {}))
    return result


def required_properties(schema: dict) -> set[str]:
    result = set(schema.get("required", []))
    for part in schema.get("allOf", []):
        result.update(part.get("required", []))
    return result


def base_types(schema: dict) -> list[str]:
    return [part["$ref"].rsplit("/", 1)[-1] for part in schema.get("allOf", []) if "$ref" in part]


def generate(spec: dict) -> tuple[str, str]:
    schemas = spec["components"]["schemas"]
    # Hash the spec as CI sees it: normalize CRLF checkouts (Windows
    # core.autocrlf) so the embedded digest is identical everywhere.
    digest = hashlib.sha256(SPEC.read_bytes().replace(b"\r\n", b"\n")).hexdigest()
    go_lines = [
        "// Code generated by tools/sdkgen.py; DO NOT EDIT.",
        f"// OpenAPI SHA256: {digest}",
        "package fluxa",
        "",
    ]
    py_lines = [
        "# Code generated by tools/sdkgen.py; DO NOT EDIT.",
        f"# OpenAPI SHA256: {digest}",
        "from __future__ import annotations",
        "",
        "from typing import Any, Required, TypedDict",
        "",
    ]

    for name, schema in schemas.items():
        base = base_types(schema)
        fields = properties(schema)
        required = required_properties(schema)

        # A schema with no properties and no allOf base is not a struct. Emitting
        # `type X struct { map[string]any }` is invalid Go — only named types can
        # be embedded — and gofmt rejects it, so the generator fails outright
        # rather than producing a usable model. Map the schema to the Go or
        # Python type it actually describes instead.
        if not base and not fields:
            go_alias, py_alias = scalar_alias(schema)
            if go_alias is not None:
                go_lines.append(f"type {pascal(name)} {go_alias}")
                go_lines.append("")
                py_lines.append(f"{pascal(name)} = {py_alias}")
                py_lines.append("")
                continue

        go_lines.append(f"type {pascal(name)} struct {{")
        for parent in base:
            go_lines.append(f"\t{pascal(parent)}")
        for key, field in fields.items():
            typ = go_type(field)
            optional = key not in required
            if optional and typ not in ("any",) and not typ.startswith("[]") and not typ.startswith("map["):
                typ = "*" + typ
            tag = f'json:"{key}' + (",omitempty" if optional else "") + '"'
            go_lines.append(f"\t{pascal(key)} {typ} `{tag}`")
        go_lines.extend(["}", ""])

        py_base = ", ".join(pascal(parent) for parent in base) or "TypedDict"
        py_lines.append(f"class {pascal(name)}({py_base}, total=False):")
        for key, field in fields.items():
            typ = python_type(field)
            if field.get("nullable"):
                typ += " | None"
            if key in required:
                py_lines.append(f"    {key}: Required[{typ}]")
            else:
                py_lines.append(f"    {key}: {typ}")
        if not fields and not base:
            py_lines.append("    pass")
        py_lines.append("")

    go_source = subprocess.run(
        ["gofmt"], input="\n".join(go_lines), text=True, capture_output=True, check=True
    ).stdout
    return go_source, "\n".join(py_lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = parser.parse_args()
    generated = dict(zip((GO_OUTPUT, PY_OUTPUT), generate(yaml.safe_load(SPEC.read_text()))))
    stale = []
    for path, content in generated.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("Generated SDK models are stale:", *(str(path) for path in stale), sep="\n  ", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())